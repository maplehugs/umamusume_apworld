"""Concert Theater songs -- granted on their REAL unlock conditions.

THE TABLE
---------
`app/data/concert_unlocks.json`, generated by tools/gen_concert_unlocks.py:
every song with a theater live (live_data.has_live=1) in either region, its
unlock rule, and the evidence for it. master.mdb carries no per-song reward
rows, so the rules are curated there from real captures, master's own
acquisition text (text_data 252) and the Concert Theater wiki, in that order
of trust. Edit the generator, not the JSON.

One table serves both regions: music_id and race_instance ids are shared, and
the story episode ids that differ are stored per region. A song this region's
live_data does not carry (yet) is never granted -- see _available.

WHEN A SONG ARRIVES
-------------------
Where the real server hands it out, on the reply that earns it -- never by a
catch-up pass at career end:

  * career race wins       -> race_end            data.add_music
  * Unity Cup finals win   -> team_race_end       data.add_music
  * Trackblazer Climax     -> the final leg's race_end
  * Grand Concert          -> single_mode_live/live_start  data.add_music
  * Island complete (DYI)  -> pioneer_live         data.add_music
  * Mecha's concert        -> mecha_live           data.add_music
  * scenario ending story  -> the reply that queues that story (story_seen)
  * main / extra / event stories -> their first_clear / story_clear,
                              data.add_music_array
  * distributed songs      -> the present box, once per account (on login)

Captures show `add_music` (singular) is a {music_id, acquisition_time} dict or
null. Songs land straight in music_list_state, the key collection.py serves as
load/index's music_list.
"""

from __future__ import annotations

import functools
import json
import logging
import os
import time

from . import master_data, region

log = logging.getLogger("uma-server")

MUSIC_LIST_KEY = "music_list_state"      # [{music_id, acquisition_time}, ...]
DEFAULTS_MAILED_KEY = "concerts_default_mailed"   # [music_id, ...] already mailed
_MUSIC_REWARD_TYPE = 80                  # presents reward_type for music
_DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                     "data", "concert_unlocks.json")


@functools.lru_cache(maxsize=1)
def table() -> tuple:
    try:
        with open(_DATA, encoding="utf-8") as fh:
            return tuple(json.load(fh).get("songs") or ())
    except Exception:
        log.exception("concert unlock table unreadable at %s", _DATA)
        return ()


def _songs(*kinds) -> list:
    return [s for s in table() if s["kind"] in kinds]


@functools.lru_cache(maxsize=None)
def _release(music_id: int):
    """This region's live_data start_date for the song, or None if absent."""
    row = master_data.query_one(
        "SELECT start_date FROM live_data WHERE music_id=?", (music_id,))
    return int(row["start_date"]) if row else None


def _available(music_id: int) -> bool:
    start = _release(int(music_id))
    return start is not None and start <= time.time()


def _now() -> str:
    # Same clock as the present box's create_time: server-local wall time,
    # which is what the captures' acquisition_time reads as (JST on JP).
    return time.strftime("%Y-%m-%d %H:%M:%S")


def owned(full_state: dict) -> set:
    return {m.get("music_id") for m in (full_state.get(MUSIC_LIST_KEY) or ())
            if isinstance(m, dict)}


def grant(full_state: dict, music_id: int):
    """Add one song to the account. Returns the wire {music_id,
    acquisition_time} the first time, None if already owned or not in this
    region. Mutates full_state; the caller saves."""
    music_id = int(music_id)
    if music_id in owned(full_state) or not _available(music_id):
        return None
    entry = {"music_id": music_id, "acquisition_time": _now()}
    full_state.setdefault(MUSIC_LIST_KEY, []).append(entry)
    log.info("concerts: unlocked %s (%s)", music_id, _title(music_id))
    return dict(entry)


def _grant_first(full_state: dict, music_ids) -> dict | None:
    """Grant every song in music_ids, report the first. add_music is a single
    object, so a reply that earns two songs announces one; the other is still
    owned and shows in the theater after the next load."""
    first = None
    for mid in music_ids:
        got = grant(full_state, mid)
        if got and first is None:
            first = got
    return first


# ---------------------------------------------------------- career races ---

@functools.lru_cache(maxsize=None)
def _program_race(program_id: int):
    row = master_data.query_one(
        "SELECT p.race_instance_id, r.grade FROM single_mode_program p "
        "JOIN race_instance ri ON ri.id = p.race_instance_id "
        "JOIN race r ON r.id = ri.race_id WHERE p.id=?", (program_id,))
    return (int(row["race_instance_id"]), int(row["grade"])) if row else (None, None)


def race_won_songs(chara_info: dict, program_id, result_rank: int) -> list:
    """music_ids a first place in this career race earns (owned or not)."""
    if int(result_rank or 0) != 1 or not program_id:
        return []
    instance, grade = _program_race(int(program_id))
    if instance is None:
        return []
    scenario_id = int((chara_info or {}).get("scenario_id") or 0)
    out = []
    for song in _songs("win_race", "win_grade_at_most"):
        p = song.get("params") or {}
        if p.get("scenario_id") and int(p["scenario_id"]) != scenario_id:
            continue
        if song["kind"] == "win_race":
            if instance in (p.get("race_instance_ids") or ()):
                out.append(song["music_id"])
        elif grade >= int(p.get("grade") or 0):
            out.append(song["music_id"])
    return out


def on_race_end(full_state: dict, chara_info: dict, race_ctx: dict,
                result_rank: int):
    """The add_music for a career race_end. Call once per race (inside the
    end_committed guard) and cache the result for retries."""
    ids = race_won_songs(chara_info, race_ctx.get("program_id"), result_rank)
    if int((chara_info or {}).get("scenario_id") or 0) == 4 and _won_climax(full_state):
        ids += [s["music_id"] for s in _songs("ts_climax")]
    return _grant_first(full_state, ids)


def _won_climax(full_state: dict) -> bool:
    """Trackblazer: the third Climax leg is banked and the trainee tops the
    cumulative standings (the turn-78 objective's own reading of 'won')."""
    try:
        from .scenarios.trackblazer import impl as tb
    except Exception:
        return False
    climax = (tb.state(full_state).get("climax") or {})
    return len(climax.get("results") or ()) >= 3 and tb.climax_ranking(full_state) == 1


# ---------------------------------------------------- scenario milestones ---

def on_scenario(full_state: dict, kind: str):
    """add_music for a scenario milestone: 'uc_finals', 'grand_concert',
    'special_grand_concert', 'pioneer_live', 'mecha_live', 'cook_live', 'sport_live'."""
    return _grant_first(full_state, [s["music_id"] for s in _songs(kind)])


@functools.lru_cache(maxsize=1)
def _story_triggers() -> dict:
    return {int(sid): s["music_id"] for s in _songs("story_seen")
            for sid in (s.get("params") or {}).get("story_ids") or ()}


def attach_story_songs(viewer_id, endpoint: str, response: dict) -> dict:
    """Dispatch post-hook for career replies: a reply that queues a scenario's
    song-bearing story (Onsen's two endings, Ramen's 極 festival, ...) also
    carries that song as add_music. Cheap when nothing matches -- state is
    only touched for a trigger story."""
    data = response.get("data") if isinstance(response, dict) else None
    if not isinstance(data, dict) or data.get("add_music"):
        return response
    events = data.get("unchecked_event_array")
    if not events or not isinstance(events, list):
        return response
    triggers = _story_triggers()
    hits = [triggers[int(e.get("story_id") or 0)] for e in events
            if isinstance(e, dict) and int(e.get("story_id") or 0) in triggers]
    if not hits:
        return response
    from . import state as state_store
    full_state = state_store.get_state(viewer_id) or {}
    got = _grant_first(full_state, hits)
    if got:
        state_store.save_state(viewer_id, full_state)
        data["add_music"] = got
    return response


# ---------------------------------------------------------------- stories ---

def _story_songs(kind: str, episode_id) -> list:
    reg = region.CURRENT_REGION.get()
    return [s["music_id"] for s in _songs(kind)
            if ((s.get("params") or {}).get("episode_ids") or {}).get(reg) == episode_id]


def on_story_clear(full_state: dict, kind: str, episode_id) -> list:
    """add_music_array for main_story / extra_story / story_event clears.
    kind is the table's kind ('main_story', 'extra_story', 'story_event')."""
    out = []
    for mid in _story_songs(kind, episode_id):
        got = grant(full_state, mid)
        if got:
            out.append(got)
    return out


# ------------------------------------------------------------------ login ---

def on_login(full_state: dict) -> bool:
    """Run from load/index. True if full_state changed.

    1. Distributed songs go to the present box once per account, as the
       Global capture shows for a fresh account (present/receive_all).
    2. Story songs an account already earned (an episode cleared before this
       unlock model existed) are granted silently, so nobody has to re-read a
       story to get a song they are owed."""
    changed = False
    mailed = full_state.setdefault(DEFAULTS_MAILED_KEY, [])
    have = owned(full_state)
    from .handlers import presents
    for song in _songs("default"):
        mid = song["music_id"]
        if mid in mailed or not _available(mid):
            continue
        mailed.append(mid)
        changed = True
        if mid not in have:
            presents.send(full_state, _MUSIC_REWARD_TYPE, mid, 1)

    from .handlers import stories
    st = full_state.get(stories.STORY_STATE_KEY) or {}
    cleared = {"main_story": st.get("main_cleared"),
               "extra_story": st.get("extra_cleared"),
               "story_event": st.get("story_event_cleared")}
    for kind, episodes in cleared.items():
        for episode_id in episodes or ():
            if on_story_clear(full_state, kind, episode_id):
                changed = True
    return changed


def _title(music_id: int):
    row = master_data.query_one(
        "SELECT text FROM text_data WHERE category=16 AND [index]=?", (music_id,))
    return row["text"] if row else None
